"""从仓库内单一字形/文本描述生成共享 ROM，不依赖旧工作区或外部字体。"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    from build_game_mode_assets import generate, TARGET
    for asset_name, asset_bytes in generate().items():
        (TARGET / asset_name).write_bytes(asset_bytes)
    rhythm=json.loads((ROOT/"assets/game_modes.json").read_text(encoding="utf-8"))["rhythm"]
    capacity=rhythm["reserve_max"]*60
    fill_pixels=rhythm["reserve_fill_pixels"]
    (TARGET / "reserve_fill.mem").write_text("".join(f"{(0 if n==0 else max(1,n*fill_pixels//capacity)):02x}\n" for n in range(capacity+1)),encoding="ascii")
    data = json.loads((ROOT / "assets/story_ui.json").read_text(encoding="utf-8"))
    chars = data["characters"]
    font = data["font_rows"]
    assert len(set(chars)) == len(chars) <= 64
    assert chars.startswith(" ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
    assert len(font) == 1024 and all(0 <= x <= 255 for x in font)
    assert any(font) and all(x == 0 for x in font[:16])
    text = []
    header = ["// 由 tools/build_story_assets.py 生成，修改 assets/story_ui.json 后重建。"]
    names = {" ": "SPACE", "-": "DASH", ":": "COLON", "/": "SLASH",
             ".": "DOT", "!": "BANG", "?": "QUESTION", "+": "PLUS"}
    for i, c in enumerate(chars):
        header.append(f"    localparam [5:0] CHAR_{names.get(c, c)} = 6'd{i};")
    for name, value in data["texts"].items():
        offset = len(text)
        if isinstance(value, list):
            assert len(value) == 2 and all(len(line) <= 26 for line in value), name
            value = "".join(line.ljust(32) for line in value)
        assert len(value) <= 127 and all(c in chars for c in value), name
        text.extend(chars.index(c) for c in value)
        header.append(f"    localparam [9:0] TXT_{name} = 10'd{offset};")
        header.append(f"    localparam [6:0] LEN_{name} = 7'd{len(value)};")
    modes = data["modes"]
    assert 1 <= len(modes) <= 16
    header.append(f"    localparam [4:0] STORY_MODE_COUNT = 5'd{len(modes)};")
    for func, width, prefix, fallback in [("story_mode_text",9,"TXT", "TXT_SOLO"), ("story_mode_length",6,"LEN","LEN_SOLO")]:
        header += [f"    function [{width}:0] {func};", "    input [3:0] id;", "    begin case(id)"]
        for i, mode in enumerate(modes):
            assert mode["text"] in data["texts"]
            header.append(f"        4'd{i}: {func}={prefix}_{mode['text']};")
        header += [f"        default: {func}={fallback};", "    endcase end", "    endfunction"]
    assert len(text) <= 1024, "Text capacity exceeded"
    memory = font + text + [0] * (1024 - len(text))
    target = ROOT / "Tetris.srcs/sources_1/new"
    (target / "story_font.mem").write_text(
        "".join(f"{x:02x}\n" for x in memory), encoding="ascii", newline="\n")
    (target / "story_text_ids.vh").write_text(
        "\n".join(header) + "\n", encoding="gbk", newline="\n")
    # 菜单计数与已接入玩法共用注册表；新增模式必须明确给出人数配置。
    for mode in modes:
        assert isinstance(mode["duo"], bool)
    state_file = target / "Game_state_machine.v"
    state = state_file.read_text(encoding="gbk")
    state, count = re.subn(r"parameter \[3:0\]CHOOSE_MAX = 4'd\d+;",
                          f"parameter [3:0]CHOOSE_MAX = 4'd{len(modes)-1};", state)
    assert count == 1
    state_file.write_text(state, encoding="gbk", newline="\n")
    top_file = target / "Tetris.v"
    top = top_file.read_text(encoding="gbk")
    expression = " || ".join(f"(choose_cnt == 4'd{i})" for i, mode in enumerate(modes) if mode["duo"]) or "1'b0"
    top, count = re.subn(r"wire duo = .*?;", f"wire duo = {expression};", top)
    assert count == 1
    top_file.write_text(top, encoding="gbk", newline="\n")
    palette = data["palette_rgb"]
    assert len(palette) == 56 and len(set(palette)) == 56
    colors = ["    function [23:0] story_palette;", "    input [5:0] index;", "    begin", "        case(index)"]
    colors += [f"        6'd{i}: story_palette=24'h{rgb};" for i, rgb in enumerate(palette)]
    colors += ["        default: story_palette=24'h000000;", "        endcase", "    end", "    endfunction"]
    (target / "story_palette.vh").write_text("\n".join(colors)+"\n", encoding="ascii", newline="\n")
    # Same palette across RGB output, synchronous network projection, and PC fallback.
    bits = data["palette_hash_bits"]
    hashes = [sum(((int(rgb, 16) >> bit) & 1) << (len(bits)-1-j) for j, bit in enumerate(bits)) for rgb in palette]
    assert len(set(hashes)) == 56 and len(bits) == 8
    projection = ", ".join(f"rgb[{bit}]" for bit in bits)
    mapping = "\n".join(f"  rom[8'h{h:02X}] = 6'd{i};" for i,h in enumerate(hashes))
    mapper = """// Generated by tools/build_story_assets.py; 56-color collision-free projection.
module rgb_to_palette(input Clk,input [23:0] rgb,output reg [5:0] code);
wire [7:0] hash = {PROJECTION};
(* rom_style = "block" *) reg [5:0] rom[0:255];
integer i;
initial begin
  for(i=0;i<256;i=i+1)rom[i]=0;
MAPPING
end
always @(posedge Clk)code<=rom[hash];
endmodule
""".replace("PROJECTION",projection).replace("MAPPING",mapping)
    (target / "rgb_to_palette.v").write_text(mapper,encoding="gbk",newline="\n")
    network = target / "net_screen_tx.v"
    source = network.read_text(encoding="gbk")
    def pal_entry(m):
        rgb=palette[int(m.group(1))]
        return f"6'd{int(m.group(1))}: pal_rgb = 24'h{rgb};"
    source,n = re.subn(r"[56]'d(\d+):\s+pal_rgb\s*=\s*24'h[0-9A-Fa-f_]+;",pal_entry,source)
    assert n==56
    network.write_text(source,encoding="gbk",newline="\n")
    pc=ROOT / "pc/net_screen_view.py"
    original_pc=pc.read_text(encoding="utf-8")
    source=original_pc
    table="DEFAULT_PAL = {\n"+"".join(f"    {i}:({int(c[:2],16)},{int(c[2:4],16)},{int(c[4:],16)}),\n" for i,c in enumerate(palette))+"}"
    source,n=re.subn(r"DEFAULT_PAL = \{.*?\n\}",lambda m:table,source,flags=re.S)
    assert n==1
    if source!=original_pc:
        pc.write_text(source,encoding="utf-8",newline="\n")
    sprites = json.loads((ROOT / "assets/story_sprites.json").read_text(encoding="utf-8"))["indices"]
    assert len(sprites)==4096 and all(0<=x<=3 for x in sprites)
    (target / "story_sprites.mem").write_text("".join(f"{x:x}\n" for x in sprites),encoding="ascii",newline="\n")
    print(f"STORY_ASSETS_PASS glyphs={len(chars)} text_bytes={len(text)} rom_bytes={len(memory)}")


if __name__ == "__main__":
    main()
