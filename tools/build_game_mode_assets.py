"""从单一模式配置生成参数、固定残骸模板及输入指纹。"""
import argparse
import hashlib
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "Tetris.srcs/sources_1/new"


def layouts(width, counts):
    gaps = [width - n for n in counts]
    used, bases = set(), []
    for fraction in (0.2, 0.4, 0.6, 0.8):
        candidates = []
        for start in range(width - gaps[0] + 1):
            for directions in itertools.product((0, -1), repeat=len(gaps)-1):
                positions = [start]
                for direction in directions:
                    positions.append(positions[-1] + direction)
                if any(x < 0 or x + gap > width for x, gap in zip(positions, gaps)):
                    continue
                rows = tuple(((1 << width)-1) ^ (((1 << gap)-1) << x)
                             for x, gap in zip(positions, gaps))
                mirror = tuple(int(f"{row:0{width}b}"[::-1], 2) for row in rows)
                if rows == mirror or rows in used or mirror in used:
                    continue
                distance = abs(start + gaps[0]/2 - width*fraction)
                candidates.append((distance, positions, rows, mirror))
        assert candidates, (width, counts)
        _, _, rows, mirror = min(candidates)
        bases.extend((rows, mirror))
        used.update((rows, mirror))
    assert len(set(bases)) == 8
    return bases[::2] + bases[1::2]


def generate():
    source = ROOT / "assets/game_modes.json"
    config = json.loads(source.read_text(encoding="utf-8"))
    assert 0 < config["score_max"] <= 999999
    assert 0 < config["lines_max"] <= 999999
    assert 0 < config["seconds_max"] <= 5999
    minutes, seconds = divmod(config["seconds_max"], 60)
    time_bcd = ((minutes//10)<<12) | ((minutes%10)<<8) | ((seconds//10)<<4) | (seconds%10)
    header = ["// Generated by tools/build_game_mode_assets.py; do not edit."]
    header += [f"localparam [19:0] MODE_SCORE_MAX=20'd{config['score_max']};",
               f"localparam [19:0] MODE_LINES_MAX=20'd{config['lines_max']};",
               f"localparam [15:0] MODE_TIME_BCD_MAX=16'h{time_bcd:04x};",
               "function [7:0] mode_endless_step; input two; begin",
               f"mode_endless_step=two?8'd{config['endless_step'][1]}:8'd{config['endless_step'][0]};",
               "end endfunction"]
    fields = {name: [] for name in ("target", "initial", "step", "total", "half")}
    words, index, percentages = [], [], []
    for duo, width in enumerate((20, 24)):
        for level, item in enumerate(config["levels"]):
            counts = [item["bottom_blocks"][duo]-k for k in range(item["height"])]
            total = sum(counts)
            threshold = (item["half_threshold_override"][duo]
                         if item["half_threshold_override"] else (2*total+4)//5)
            percentages.extend(max(0, (total-left)*100//total) if left<=total else 0
                               for left in range(128))
            subsets = {sum(n for k, n in enumerate(counts) if mask & (1 << k))
                       for mask in range(1, 1 << len(counts))}
            assert any(0 < n <= threshold for n in subsets), "HALF unreachable"
            for name, value in (("target", item["target"][duo]), ("initial", item["initial_speed"]),
                                ("step", item["step"][duo]), ("total", total), ("half", threshold)):
                fields[name].append(value)
            for layout, rows in enumerate(layouts(width, counts)):
                intersection = (1 << width)-1
                board = [0]*20
                for k, row in enumerate(rows):
                    assert row.bit_count() == counts[k]
                    assert width-row.bit_count() >= (5 if duo else 4)
                    intersection &= ~row
                    board[19-k] = row
                assert intersection.bit_count() >= (3 if duo else 2)
                words.extend(board)
                index.append({"duo": duo, "level": level, "layout": layout,
                              "rows": board, "total": total, "half": threshold})
    for name, values in fields.items():
        header += [f"function [7:0] mode_{name};", "input two; input [1:0] ship;",
                   "begin case({two,ship})"]
        header += [f"3'd{i}:mode_{name}=8'd{v};" for i, v in enumerate(values)]
        header += [f"default:mode_{name}=0;", "endcase end endfunction"]
    outputs = {"game_mode_params.vh": ("\n".join(header)+"\n").encode("ascii"),
               "story_debris.mem": "".join(f"{w:06x}\n" for w in words).encode("ascii"),
               "story_debris_percent.mem": "".join(f"{v:02x}\n" for v in percentages).encode("ascii")}
    manifest = {"version": config["version"], "template_version": config["template_version"],
                "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                "outputs": {name: hashlib.sha256(data).hexdigest() for name, data in outputs.items()},
                "layouts": index}
    outputs["game_mode_manifest.json"] = (json.dumps(manifest, indent=2)+"\n").encode("utf-8")
    return outputs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, data in generate().items():
        path = TARGET / name
        if args.check:
            assert path.read_bytes() == data, f"Stale generated resource: {path}"
        else:
            path.write_bytes(data)
    print("GAME_MODE_ASSETS_PASS configs=8 layouts=64 HALF_numeric=8/8")


if __name__ == "__main__":
    main()
